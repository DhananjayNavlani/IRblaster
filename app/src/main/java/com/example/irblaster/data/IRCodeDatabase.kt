        VIZIO("Vizio", "📺"),
        TCL("TCL", "📺"),
        HISENSE("Hisense", "📺"),
        SHARP("Sharp", "📺")
    }

    data class IRCode(
        val name: String,
        val emoji: String,
        val frequency: Int,
        val pattern: IntArray
    ) {
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (javaClass != other?.javaClass) return false
            other as IRCode
            return name == other.name && pattern.contentEquals(other.pattern)
        }
        override fun hashCode(): Int = 31 * name.hashCode() + pattern.contentHashCode()
    }

    fun getCodesForBrand(brand: Brand): Map<String, List<IRCode>> {
        return when (brand) {
            Brand.SAMSUNG -> samsungCodes
            Brand.LG -> lgCodes
            Brand.SONY -> sonyCodes
            Brand.PANASONIC -> panasonicCodes
            Brand.PHILIPS -> philipsCodes
            Brand.TOSHIBA -> toshibaCodes
            Brand.VIZIO -> vizioCodes
            Brand.TCL -> tclCodes
            Brand.HISENSE -> hisenseCodes
            Brand.SHARP -> sharpCodes
        }
    }

